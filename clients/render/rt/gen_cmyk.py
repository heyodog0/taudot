"""Generates rt/cmyk_table.h: CMYK → sRGB as a PDF viewer shows it, sampled on a 9×9×9×9 grid.

The conversion PDF viewers use (Acrobat, PDF.js, MuPDF: a SWOP-like press profile) is measured, not copied: a PDF of
6561 rectangles, one per grid point, is drawn by any viewer's rasteriser at one pixel per rectangle, and the pixels
are the table. The colours are measurements; no profile or code ships. rt/apple.c interpolates between grid points
(mean error 0.6 levels on 5000 random colours, exact at the grid points, which hold xcolor's named colours).

    uv run --with pillow python gen_cmyk.py grid.pdf          # writes grid.pdf
    mutool draw -r 72 -o grid.png grid.pdf                    # or any viewer at 72 dpi
    uv run --with pillow python gen_cmyk.py grid.png          # writes cmyk_table.h
"""
import itertools
import sys
from pathlib import Path

N, W = 9, 81
vals = [i / (N - 1) for i in range(N)]
cells = list(itertools.product(vals, repeat=4))
H = (len(cells) + W - 1) // W
arg = Path(sys.argv[1])

if arg.suffix == ".pdf":
    ops = [f"{c:.4f} {m:.4f} {y:.4f} {k:.4f} k {i % W} {H - 1 - i // W} 1 1 re f" for i, (c, m, y, k) in enumerate(cells)]
    content = "\n".join(ops).encode()
    objs = [b"<< /Type /Catalog /Pages 2 0 R >>", b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {W} {H}] /Contents 4 0 R >>".encode(),
            b"<< /Length %d >>\nstream\n" % len(content) + content + b"\nendstream"]
    out, offs = b"%PDF-1.4\n", []
    for i, o in enumerate(objs):
        offs.append(len(out))
        out += b"%d 0 obj\n" % (i + 1) + o + b"\nendobj\n"
    x = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1) + b"".join(b"%010d 00000 n \n" % o for o in offs)
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, x)
    arg.write_bytes(out)
else:
    from PIL import Image
    img = Image.open(arg).convert("RGB")
    px = [img.getpixel((i % W, i // W)) for i in range(len(cells))]
    lines = ["/* Generated by gen_cmyk.py: CMYK → sRGB on a 9^4 grid, index ((c*9 + m)*9 + y)*9 + k. */",
             "static const unsigned char cmyk_table[9 * 9 * 9 * 9][3] = {"]
    for i in range(0, len(px), 8):
        lines.append("  " + " ".join("{%d,%d,%d}," % p for p in px[i:i + 8]))
    lines.append("};")
    (Path(__file__).parent / "cmyk_table.h").write_text("\n".join(lines) + "\n")
