# Generates tables.h for glyphlists.c: code page 437 → Unicode (Python's cp437 codec), and the 258 glyphs of
# TrueType's standard Macintosh order (fontTools' standardGlyphOrder) → Unicode through the Adobe Glyph List
# (fontTools.agl; 0 when a name isn't in it). Our own code (MIT).
#   uv run --with fonttools==4.60.1 clients/render/fonts/gen_tables.py > clients/render/fonts/tables.h
from fontTools.agl import AGL2UV
from fontTools.ttLib.standardGlyphOrder import standardGlyphOrder

cp437 = [ord(bytes([i]).decode("cp437")) for i in range(256)]
tt = [AGL2UV.get(n, 0) for n in standardGlyphOrder]
assert len(tt) == 258


def rows(v):
    return "\n".join("    " + ", ".join(str(x) for x in v[i:i + 16]) + "," for i in range(0, len(v), 16))


print("/* tables.h: GENERATED by gen_tables.py; do not edit. */")
print("static const unsigned short tf_cp437[256] = {\n" + rows(cp437) + "\n};")
print("static const unsigned short tf_tt_standard[258] = {\n" + rows(tt) + "\n};")
